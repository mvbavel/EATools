def _base_name(name: str) -> str:
    """'ADP Workforce Now (NTT GN)' -> 'ADP Workforce Now'. Alfabet suffixes the owning org."""
    return re.sub(r"\s*\([^()]*\)\s*$", "", name).strip()


def _payload_from_records(records: list[dict], source: str, summary: str) -> dict:
    """Normalised Alfabet application records -> an extraction-shaped payload.

    A record carries Alfabet *values* under neutral keys: name, ref, alias, shortname,
    description, criticality, objectstate, hostingtype, capability, platform, evidence.
    Both the EDC reader and the REST import produce these, so both map identically.
    """
    applications: list[dict] = []
    capabilities: dict[str, dict] = {}
    components: dict[str, dict] = {}
    for rec in records:
        name = (rec.get("name") or "").strip()
        if not name:
            continue
        capability = (rec.get("capability") or "").strip()
        if capability and capability not in capabilities:
            capabilities[capability] = {
                "name": capability,
                "description": "",
                "level": 1,
                "parent": "",
                "evidence": "Alfabet primary capability",
                "confidence": "high",
                "_source": source,
            }
        platform = (rec.get("platform") or "").strip()
        if platform and platform not in components:
            components[platform] = {
                "name": platform,
                "description": "",
                "category": "unknown",
                "evidence": "Alfabet platform (ICT object)",
                "confidence": "high",
                "_source": source,
            }

        # Extra names this app may appear under in a diagram. merge.py only links on them
        # when exactly one entity claims the name.
        match_names = [(rec.get("shortname") or "").strip()]
        base = _base_name(name)
        if base != name:
            match_names.append(base)

        applications.append(
            {
                "name": name,
                "alias": (rec.get("alias") or "").strip(),
                "description": (rec.get("description") or "").strip(),
                "business_criticality": _CRITICALITY.get((rec.get("criticality") or "").strip(), "unknown"),
                "lifecycle": _OBJECT_STATE.get((rec.get("objectstate") or "").strip(), "unknown"),
                "hosting": _HOSTING_TYPE.get((rec.get("hostingtype") or "").strip(), "unknown"),
                "capabilities": [capability] if capability else [],
                "data_objects": [],
                "it_components": [platform] if platform else [],
                "evidence": rec.get("evidence", ""),
                "confidence": "high",
                "_source": source,
                "_alfabet_ref": (rec.get("ref") or "").strip(),
                "_match_names": [n for n in match_names if n],
            }
        )

    return {
        "diagram_summary": summary.format(count=len(applications)),
        "applications": applications,
        "capabilities": list(capabilities.values()),
        "it_components": list(components.values()),
        "data_objects": [],
        "interfaces": [],
        "open_questions": [],
    }


def read_edc(filename: str, data: bytes) -> dict:
    """Turn an EDC workbook into an extraction-shaped payload (no model call)."""
    wb = EdcWorkbook(filename, data)
    col = wb.col_of.get
    records = []
    for row in wb.rows:
        ref = row.get(col(_REFERENCE)).strip()
        records.append(
            {
                "name": row.get(col("Name")),
                "ref": ref,
                "alias": row.get(col("SAG_Alias")),
                "shortname": row.get(col("ShortName")),
                "description": row.get(col("Description")),
                "criticality": row.get(col("Criticality")),
                "objectstate": row.get(col("ObjectState")),
                "hostingtype": row.get(col("HostingType")),
                "capability": row.get(col("Domain")),
                "platform": row.get(col("ICTObject")),
                "evidence": f"Alfabet {wb.data_sheet} row {row.number}" + (f" (Reference {ref})" if ref else ""),
            }
        )
    payload = _payload_from_records(records, filename, f"Alfabet EDC import: {{count}} applications from {filename}.")
    if not payload["applications"]:
        raise NotEdcWorkbook(f"{filename}: EDC workbook has no named rows")
    return payload


# Alfabet REST report rows: `Values` keys are the report's lower-case column names.
# Observed in the Application-Mark report; a column the report lacks (it has no
# criticality) simply comes back blank and maps to "unknown".
_API_VALUE_KEYS = {
    "name": "name",
    "alias": "alias",
    "shortname": "shortname",
    "description": "description",
    "criticality": "criticality",
    "objectstate": "objectstate",
    "hostingtype": "hostingtype",
    "capability": "primarycapability",
    "platform": "platform",
}


def payload_from_api(objects: list[dict], source: str) -> dict:
    """Alfabet REST `Objects` (ClassName/RefStr/Values) -> an extraction-shaped payload."""
    records = []
    for obj in objects:
        if not isinstance(obj, dict) or obj.get("ClassName", "Application") != "Application":
            continue
        values = obj.get("Values") or {}
        rec = {key: _api_text(values.get(api_key)) for key, api_key in _API_VALUE_KEYS.items()}
        rec["ref"] = _api_text(obj.get("RefStr"))
        rec["evidence"] = f"Alfabet API, {source}" + (f" (Reference {rec['ref']})" if rec["ref"] else "")
        records.append(rec)
    return _payload_from_records(records, source, f"Alfabet API import: {{count}} applications ({source}).")


def _api_text(value) -> str:
    return "" if value is None else str(value)


