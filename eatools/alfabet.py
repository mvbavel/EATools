_ROW_RE = re.compile(r"<row\b([^>]*?)(?:/>|>(.*?)</row>)", re.S)
_CELL_RE = re.compile(r"<c\b([^>]*?)(?:/>|>(.*?)</c>)", re.S)
_ATTR_RE = re.compile(r'([\w:]+)="([^"]*)"')
_V_RE = re.compile(r"<v>(.*?)</v>", re.S)
_T_RE = re.compile(r"<t\b[^>]*>(.*?)</t>", re.S)
_EXCEL_ESC_RE = re.compile(r"_x([0-9A-Fa-f]{4})_")
_COL_RE = re.compile(r"[A-Z]+")


def _col_index(letters: str) -> int:
    n = 0
    for ch in letters:
        n = n * 26 + (ord(ch) - 64)
    return n


def _col_letters(index: int) -> str:
    out = ""
    while index:
        index, rem = divmod(index - 1, 26)
        out = chr(65 + rem) + out
    return out


def _decode(text: str) -> str:
    """XML-unescape, then undo Excel's _xHHHH_ escapes for control characters."""
    return _EXCEL_ESC_RE.sub(lambda m: chr(int(m.group(1), 16)), html.unescape(text))


@dataclass
class _Cell:
    col: str
    attrs: str  # raw attribute text, kept so styles survive a rewrite
    inner: str  # raw inner XML
    value: str  # decoded display value


@dataclass
class _Row:
    number: int
    attrs: str
    cells: dict[str, _Cell] = field(default_factory=dict)

    def get(self, col: str | None) -> str:
        if not col or col not in self.cells:
            return ""
        return self.cells[col].value


class EdcWorkbook:
    """A parsed EDC template. Holds the raw parts so export can rewrite just one sheet."""

    def __init__(self, filename: str, data: bytes) -> None:
        self.filename = filename
        try:
            self._zip = zipfile.ZipFile(io.BytesIO(data))
        except zipfile.BadZipFile:
            raise NotEdcWorkbook(f"{filename}: not a valid .xlsx file") from None
        for info in self._zip.infolist():
            if info.file_size > MAX_PART_BYTES:
                raise NotEdcWorkbook(f"{filename}: workbook part {info.filename} is too large")
        try:
            self._load()
        except (KeyError, ET.ParseError, ValueError, IndexError):
            raise NotEdcWorkbook(f"{filename}: unreadable workbook structure") from None

    # -- loading -------------------------------------------------------------

    def _text(self, part: str) -> str:
        return self._zip.read(part).decode("utf-8")

    def _load(self) -> None:
        self.shared_strings = self._read_shared_strings()
        wb = ET.fromstring(self._zip.read("xl/workbook.xml"))
        rels = ET.fromstring(self._zip.read("xl/_rels/workbook.xml.rels"))
        targets = {r.get("Id"): r.get("Target") for r in rels}

        self.sheets: dict[str, str] = {}  # sheet name -> part path
        visible: list[str] = []
        for sheet in wb.find(f"{_M}sheets"):
            target = targets[sheet.get(f"{{{_NS_R}}}id")]
            path = target.lstrip("/") if target.startswith("/") else f"xl/{target}"
            self.sheets[sheet.get("name")] = path
            if sheet.get("state") not in ("hidden", "veryHidden"):
                visible.append(sheet.get("name"))

        if "DCTDReference" not in self.sheets:
            raise NotEdcWorkbook(f"{self.filename}: not an Alfabet EDC workbook (no DCTDReference sheet)")

        self.defined_names = {
            dn.get("name"): (dn.text or "") for dn in wb.iter(f"{_M}definedName")
        }

        # caption -> Alfabet property name
        dctd_rows = self._rows("DCTDReference")
        self.caption_to_property = {
            r.get("C"): r.get("B") for r in dctd_rows[1:] if r.get("B") and r.get("C")
        }

        self.data_sheet = "Export" if "Export" in self.sheets else next(
            (n for n in visible if n != "Help"), None
        )
        if self.data_sheet is None:
            raise NotEdcWorkbook(f"{self.filename}: no data sheet found")
        self.sheet_xml = self._text(self.sheets[self.data_sheet])
        rows = self._parse_rows(self.sheet_xml)
        if not rows:
            raise NotEdcWorkbook(f"{self.filename}: data sheet is empty")
        self.header = rows[0]
        self.rows = [r for r in rows[1:] if any(c.value for c in r.cells.values())]

        # column letter <-> property (system columns keyed by caption)
        self.col_of: dict[str, str] = {}
        for col, cell in self.header.cells.items():
            caption = cell.value
            if caption in (_OPERATIONS, _REFERENCE):
                self.col_of[caption] = col
            elif caption in self.caption_to_property:
                self.col_of[self.caption_to_property[caption]] = col
        if "Name" not in self.col_of or _REFERENCE not in self.col_of:
            raise NotEdcWorkbook(f"{self.filename}: EDC data sheet lacks Name/Reference columns")

        self.picklists = self._read_picklists()
        self.mandatory = self._read_mandatory()

    def _read_shared_strings(self) -> list[str]:
        if "xl/sharedStrings.xml" not in self._zip.namelist():
            return []
        root = ET.fromstring(self._zip.read("xl/sharedStrings.xml"))
        out = []
        for si in root.findall(f"{_M}si"):
            # Plain <t> or rich-text runs <r><t>; skip phonetic <rPh> runs.
            parts = [t.text or "" for t in si.findall(f"{_M}t")]
            parts += [t.text or "" for r in si.findall(f"{_M}r") for t in r.findall(f"{_M}t")]
            out.append(_EXCEL_ESC_RE.sub(lambda m: chr(int(m.group(1), 16)), "".join(parts)))
        return out

    def _parse_rows(self, xml: str) -> list[_Row]:
        start = xml.find("<sheetData")
        end = xml.find("</sheetData>")
        if start == -1:
            return []
        body = xml[start:end] if end != -1 else xml[start:]
        rows = []
        for rm in _ROW_RE.finditer(body):
            attrs = rm.group(1)
            number = int(dict(_ATTR_RE.findall(attrs))["r"])
            row = _Row(number=number, attrs=attrs)
            for cm in _CELL_RE.finditer(rm.group(2) or ""):
                cattrs = dict(_ATTR_RE.findall(cm.group(1)))
                inner = cm.group(2) or ""
                col = _COL_RE.match(cattrs["r"]).group()
                row.cells[col] = _Cell(col, cm.group(1), inner, self._cell_value(cattrs.get("t"), inner))
            rows.append(row)
        return rows

    def _cell_value(self, cell_type: str | None, inner: str) -> str:
        if cell_type == "inlineStr":
            return _decode("".join(_T_RE.findall(inner)))
        v = _V_RE.search(inner)
        if v is None:
            return ""
        if cell_type == "s":
            return self.shared_strings[int(v.group(1))]
        return _decode(v.group(1))

    def _rows(self, sheet_name: str) -> list[dict[str, str]]:
        return [
            {col: cell.value for col, cell in row.cells.items()}
            for row in self._parse_rows(self._text(self.sheets[sheet_name]))
        ]

    def _read_picklists(self) -> dict[str, list[str]]:
        """Data-sheet column letter -> allowed values, via validation -> defined name -> range."""
        ref_cache: dict[str, dict[int, dict[str, str]]] = {}
        out: dict[str, list[str]] = {}
        for dv in re.finditer(r"<dataValidation\b([^>]*)>(.*?)</dataValidation>", self.sheet_xml, re.S):
            attrs = dict(_ATTR_RE.findall(dv.group(1)))
            if attrs.get("type") != "list":
                continue
            formula = re.search(r"<formula1>(.*?)</formula1>", dv.group(2), re.S)
            if not formula:
                continue
            target = self.defined_names.get(html.unescape(formula.group(1)).strip())
            m = re.match(r"'?(.+?)'?!\$([A-Z]+)\$(\d+):\$([A-Z]+)\$(\d+)$", target or "")
            if not m or m.group(1) not in self.sheets:
                continue
            sheet, col, first, last = m.group(1), m.group(2), int(m.group(3)), int(m.group(5))
            if sheet not in ref_cache:
                ref_cache[sheet] = {
                    r.number: {c: cell.value for c, cell in r.cells.items()}
                    for r in self._parse_rows(self._text(self.sheets[sheet]))
                }
            values = [
                ref_cache[sheet].get(n, {}).get(col, "") for n in range(first, last + 1)
            ]
            allowed = [v for v in values if v]
            for col_ref in attrs.get("sqref", "").split():
                out[_COL_RE.match(col_ref).group()] = allowed
        return out

    def _read_mandatory(self) -> list[str]:
        """Captions the Help sheet marks Mandatory=True (empty if there is no Help sheet)."""
        if "Help" not in self.sheets:
            return []
        rows = self._rows("Help")
        return [r.get("A", "") for r in rows[1:] if r.get("C", "").strip().lower() == "true"]

    # -- helpers -------------------------------------------------------------

    def caption(self, prop: str) -> str:
        col = self.col_of.get(prop)
        return self.header.get(col) if col else prop

    def picklist_match(self, prop: str, value: str) -> str | None:
        """Exact picklist spelling for `value`, or None. Free-text columns accept anything.

        Matching is case-insensitive and also ignores a leading ordinal ("8 Platform
        Delivered Services" == "Platform Delivered Services"), which Alfabet domains carry.
        """
        col = self.col_of.get(prop)
        allowed = self.picklists.get(col) if col else None
        if allowed is None:
            return value
        key = value.strip().casefold()
        for option in allowed:
            if option.strip().casefold() == key:
                return option
        for option in allowed:
            if re.sub(r"^\d+(\.\d+)*\s+", "", option.strip()).casefold() == key:
                return option
        return None


