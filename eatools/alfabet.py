"""Bizzdesign Alfabet EDC (Excel Data Capture) workbooks: import as entities, export by
filling the template.

An EDC workbook is generated by Alfabet for one object class (here: Application). Besides
the visible data sheet it carries hidden machinery Alfabet needs to accept the file back:
``DCTDReference`` (column caption -> Alfabet property), ``ReferenceData*`` sheets behind
every picklist, and an ``ALFA_RUNTIME_DCT`` document property. So export never builds a
workbook from scratch -- it rewrites only the data rows of the user's own template and
copies every other part byte-for-byte.

* `read_edc(filename, bytes) -> payload` turns each data row into an application entity
  carrying its Alfabet ``Reference`` in ``_alfabet_ref``; Primary Capability and Platform
  become capability / IT-component entities. No model call is involved.
* `build_edc(template_name, template_bytes, payload) -> zip bytes` writes matched apps as
  ``Update`` rows (existing values kept wherever the payload is blank) and unmatched apps
  as ``Create`` rows, plus an ``alfabet_report.csv`` of everything a reviewer must check.

Values are never invented: a payload value with no exact picklist entry is left blank and
reported, and missing mandatory properties (Version, dates) are reported, not defaulted.

The mapping tables below are **the tenant-adaptation seam** for Alfabet, like
``leanix.SHEETS`` is for LeanIX. They are keyed by Alfabet property name (DCTD name), not
by column caption, because captions are configurable per template.
"""

