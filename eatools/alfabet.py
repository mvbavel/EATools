@dataclass
class _Issue:
    name: str
    operation: str
    reference: str
    issue: str


class _SharedStrings:
    """Append-only view over the template's shared-string table."""

    def __init__(self, existing: list[str]) -> None:
        self.count = len(existing)
        self.index = {s: i for i, s in enumerate(existing)}
        self.added: list[str] = []

    def get(self, text: str) -> int:
        if text not in self.index:
            self.index[text] = self.count + len(self.added)
            self.added.append(text)
        return self.index[text]


def _xml_text(text: str) -> str:
    # Control characters other than tab/newline are illegal in XML; Excel's escape keeps them.
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", lambda m: f"_x{ord(m.group()):04X}_", text)
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _app_values(app: dict, wb: EdcWorkbook, issues: list[str]) -> dict[str, str]:
    """Alfabet property -> value for one application; unmappable values reported, not guessed."""
    values: dict[str, str] = {}
    for prop, getter in _EXPORT_FIELDS.items():
        if prop not in wb.col_of:
            continue
        value = str(getter(app) or "").strip()
        if not value:
            continue
        match = wb.picklist_match(prop, value)
        if match is None:
            issues.append(f"{wb.caption(prop)}: '{value}' is not in the template picklist; left unchanged")
            continue
        values[prop] = match

    hosting = app.get("hosting", "")
    if hosting not in ("", "unknown") and "HostingType" not in values:
        issues.append(f"Hosting '{hosting}' has no unambiguous Alfabet Hosting Type; left unchanged")
    crit = app.get("business_criticality", "")
    if crit not in ("", "unknown") and "Criticality" not in values:
        issues.append(f"Business criticality '{crit}' has no Alfabet equivalent; left unchanged")

    for prop, list_field in _EXPORT_PICK_FIRST.items():
        if prop not in wb.col_of:
            continue
        candidates = [c for c in app.get(list_field, []) if c]
        match = next((m for c in candidates if (m := wb.picklist_match(prop, c))), None)
        if match:
            values[prop] = match
        elif candidates:
            issues.append(
                f"{wb.caption(prop)}: none of {candidates} is in the template picklist; left unchanged"
            )
    return values


def _possible_duplicates(name: str, existing: list[tuple[str, set[str]]], cutoff: float = 0.8) -> list[str]:
    """Existing names close to `name`, also compared without their org suffix."""
    matcher = difflib.SequenceMatcher(None)
    matcher.set_seq2(name.casefold())
    scored = []
    for original, variants in existing:
        best = 0.0
        for variant in variants:
            matcher.set_seq1(variant)
            if matcher.real_quick_ratio() >= cutoff and matcher.quick_ratio() >= cutoff:
                best = max(best, matcher.ratio())
        if best >= cutoff:
            scored.append((-best, original))
    return [n for _, n in sorted(scored)[:3]]


def _cell_xml(col: str, row_number: int, style: str | None, text: str, strings: _SharedStrings) -> str:
    s = f' s="{style}"' if style else ""
    if not text:
        return f'<c r="{col}{row_number}"{s}/>'
    return f'<c r="{col}{row_number}"{s} t="s"><v>{strings.get(text)}</v></c>'


def _style_of(attrs: str) -> str | None:
    return dict(_ATTR_RE.findall(attrs)).get("s")


def _row_xml(number: int, row_attrs: str, cells: dict[str, str]) -> str:
    attrs = re.sub(r'\br="\d+"', f'r="{number}"', row_attrs, count=1)
    ordered = "".join(cells[c] for c in sorted(cells, key=_col_index))
    return f"<row{attrs}>{ordered}</row>"


def _renumber_cell(cell: _Cell, number: int) -> str:
    attrs = re.sub(r'\br="[A-Z]+\d+"', f'r="{cell.col}{number}"', cell.attrs, count=1)
    return f"<c{attrs}>{cell.inner}</c>" if cell.inner else f"<c{attrs}/>"


def build_edc(template_name: str, template_bytes: bytes, payload: dict) -> bytes:
    """Fill the EDC template with the payload's applications; return a zip (xlsx + report)."""
    wb = EdcWorkbook(template_name, template_bytes)
    strings = _SharedStrings(wb.shared_strings)
    col_of = wb.col_of
    by_ref = {r.get(col_of[_REFERENCE]).strip(): r for r in wb.rows if r.get(col_of[_REFERENCE]).strip()}
    existing_names = [
        (n, {n.casefold(), _base_name(n).casefold()})
        for n in (r.get(col_of["Name"]).strip() for r in wb.rows)
        if n
    ]
    # Create rows borrow per-column styles from the first data row (or the header).
    style_row = wb.rows[0] if wb.rows else wb.header
    style_for = {c: _style_of(cell.attrs) for c, cell in style_row.cells.items()}
    all_cols = sorted(set(wb.header.cells) | set(style_row.cells), key=_col_index)

    report: list[_Issue] = []
    out_rows: list[str] = []
    next_row = 2
    counts = {"Create": 0, "Update": 0, "unchanged": 0, "skipped": 0}

    for app in payload.get("applications", []):
        name = str(app.get("name", "")).strip()
        if not name:
            continue
        refs = [r.strip() for r in str(app.get("_alfabet_ref", "") or "").split(";") if r.strip()]
        notes: list[str] = []

        if len(refs) > 1:
            counts["skipped"] += 1
            report.append(_Issue(name, "Skipped", "; ".join(refs), "matches several Alfabet objects; keep one Reference in _alfabet_ref"))
            continue
        if refs and refs[0] not in by_ref:
            counts["skipped"] += 1
            report.append(_Issue(name, "Skipped", refs[0], "Reference not found in this template; export from the workbook it came from"))
            continue

        values = _app_values(app, wb, notes)

        if refs:
            existing = by_ref[refs[0]]
            changed = {
                prop: value
                for prop, value in values.items()
                if value.strip() != existing.get(col_of[prop]).strip()
            }
            if not changed:
                counts["unchanged"] += 1
                continue
            cells = {c: _renumber_cell(cell, next_row) for c, cell in existing.cells.items()}
            for prop, value in changed.items():
                col = col_of[prop]
                style = _style_of(existing.cells[col].attrs) if col in existing.cells else style_for.get(col)
                cells[col] = _cell_xml(col, next_row, style, value, strings)
                old = existing.get(col)
                notes.append(f"{wb.caption(prop)}: '{old}' -> '{value}'" if old else f"{wb.caption(prop)}: set to '{value}'")
            operation, ref, row_attrs = "Update", refs[0], existing.attrs
        else:
            values.setdefault("Name", name)
            if "Stereotype" in col_of and wb.picklist_match("Stereotype", _STEREOTYPE):
                values["Stereotype"] = wb.picklist_match("Stereotype", _STEREOTYPE)
            cells = {c: _cell_xml(c, next_row, style_for.get(c), "", strings) for c in all_cols}
            for prop, value in values.items():
                col = col_of[prop]
                cells[col] = _cell_xml(col, next_row, style_for.get(col), value, strings)
            filled = {wb.caption(p) for p in values}
            missing = [m for m in wb.mandatory if m not in filled]
            if missing:
                notes.append(f"mandatory in Alfabet, not known from the sources: {', '.join(missing)}")
            close = _possible_duplicates(name, existing_names)
            if close:
                notes.append(f"possible duplicate of existing: {'; '.join(close)}")
            operation, ref, row_attrs = "Create", "", style_row.attrs

        if _OPERATIONS in col_of:
            col = col_of[_OPERATIONS]
            cells[col] = _cell_xml(col, next_row, style_for.get(col), operation, strings)
        counts[operation] += 1
        out_rows.append(_row_xml(next_row, row_attrs, cells))
        for note in notes or ["ok"]:
            report.append(_Issue(name, operation, ref, note))
        next_row += 1

    xlsx = _rewrite_workbook(wb, out_rows, strings, last_row=next_row - 1)
    stem = PurePosixPath(template_name).stem or "alfabet"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{stem}_EATools.xlsx", xlsx)
        zf.writestr("alfabet_report.csv", _report_csv(report, counts))
    return buf.getvalue()


def _rewrite_workbook(wb: EdcWorkbook, out_rows: list[str], strings: _SharedStrings, last_row: int) -> bytes:
    """Copy the template, replacing only the data rows and appending new shared strings."""
    xml = wb.sheet_xml
    header_match = next(m for m in _ROW_RE.finditer(xml) if dict(_ATTR_RE.findall(m.group(1))).get("r") == "1")
    start = xml.index(">", xml.index("<sheetData")) + 1
    end = xml.index("</sheetData>")
    xml = xml[:start] + header_match.group(0) + "".join(out_rows) + xml[end:]
    last_col = max((_col_index(c) for c in wb.header.cells), default=1)
    xml = re.sub(r'<dimension ref="[^"]*"/>', f'<dimension ref="A1:{_col_letters(last_col)}{max(last_row, 1)}"/>', xml, count=1)
    # Hyperlinks and their anchors belonged to the replaced rows.
    xml = re.sub(r"<hyperlinks>.*?</hyperlinks>", "", xml, count=1, flags=re.S)

    sst_part = "xl/sharedStrings.xml"
    if sst_part not in wb._zip.namelist():
        raise NotEdcWorkbook(f"{wb.filename}: template has no shared-string table")
    sst = wb._text(sst_part)
    if strings.added:
        added = "".join(f'<si><t xml:space="preserve">{_xml_text(s)}</t></si>' for s in strings.added)
        sst = sst.replace("</sst>", added + "</sst>")
    total = strings.count + len(strings.added)
    # `count` (total references) is optional and now unknowable without a full recount.
    sst = re.sub(r'\s+count="\d+"', "", sst, count=1)
    sst = re.sub(r'uniqueCount="\d+"', f'uniqueCount="{total}"', sst, count=1)

    replaced = {wb.sheets[wb.data_sheet]: xml.encode("utf-8"), sst_part: sst.encode("utf-8")}
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for info in wb._zip.infolist():
            data = replaced.get(info.filename)
            zf.writestr(info, data if data is not None else wb._zip.read(info.filename))
    return out.getvalue()


def _report_csv(report: list[_Issue], counts: dict[str, int]) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["Name", "Operation", "Reference", "Issue"])
    for item in report:
        writer.writerow([item.name, item.operation, item.reference, item.issue])
    writer.writerow([])
    writer.writerow(
        [f"Totals: {counts['Create']} create, {counts['Update']} update, "
         f"{counts['unchanged']} matched but unchanged (omitted), {counts['skipped']} skipped"]
    )
    return b"\xef\xbb\xbf" + buf.getvalue().encode("utf-8")
