EDC_SUFFIXES = {".xlsx", ".xlsm"}
# Largest single workbook part we will inflate. A real 2,500-row template's data sheet is
# ~6 MB; the cap stops a zip bomb without getting in the way of genuine exports.
MAX_PART_BYTES = 64 * 1024 * 1024

_NS = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
_NS_R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
_M = "{%s}" % _NS

# EDC system columns: not Alfabet properties, so absent from DCTDReference.
_OPERATIONS = "Operations"
_REFERENCE = "Reference"

# ---------------------------------------------------------------------------
# Mapping seam: Alfabet picklist value <-> EATools enum
# ---------------------------------------------------------------------------

_CRITICALITY = {
    "Mission Critical": "mission_critical",
    "Business Critical": "business_critical",
    "Business Operational": "business_operational",
}
_OBJECT_STATE = {"Plan": "plan", "Active": "active", "Retired": "endOfLife"}
_LIFECYCLE_TO_STATE = {
    "plan": "Plan",
    "phaseIn": "Plan",
    "active": "Active",
    "phaseOut": "Active",
    "endOfLife": "Retired",
}
# Only one-to-one equivalents. "Externally Hosted" covers both SaaS and third-party data
# centres, and SaaS apps in practice sit under Externally *and* Cloud Hosted -- neither
# direction is safe to guess, so both stay unmapped (and are reported on export).
_HOSTING_TYPE = {"Cloud Hosted": "cloud", "Internally Hosted": "on_premise", "Hybrid": "hybrid"}


def _invert(mapping: dict[str, str]) -> dict[str, str]:
    return {v: k for k, v in mapping.items()}


# Export: Alfabet property -> getter over one application entity. Picklist columns are
# validated against the template's own reference data after the getter runs.
_EXPORT_FIELDS = {
    "Name": lambda app: app.get("name", ""),
    "SAG_Alias": lambda app: app.get("alias", ""),
    "Description": lambda app: app.get("description", ""),
    "Criticality": lambda app: _invert(_CRITICALITY).get(app.get("business_criticality", ""), ""),
    "ObjectState": lambda app: _LIFECYCLE_TO_STATE.get(app.get("lifecycle", ""), ""),
    "HostingType": lambda app: _invert(_HOSTING_TYPE).get(app.get("hosting", ""), ""),
}
# List-valued payload fields that feed a single-valued picklist: the first entry that
# exists in the picklist wins.
_EXPORT_PICK_FIRST = {
    "Domain": "capabilities",  # caption "Primary Capability"
    "ICTObject": "it_components",  # caption "Platform"
}
_STEREOTYPE = "Application"


class NotEdcWorkbook(UnsupportedFile):
    """An .xlsx that is not an Alfabet EDC export (or is too damaged to read)."""


def is_edc_filename(filename: str) -> bool:
    return PurePosixPath(filename.lower()).suffix in EDC_SUFFIXES


